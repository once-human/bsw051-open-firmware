"""Render TTF fonts into 2-bit anti-aliased bitmaps for the watch firmware (onkar_font.h).
   python3 tools/gen_font.py OUT.h        (system python: needs PIL)
Each glyph: fixed cell w x h, 4 pixels per byte (2 bits each, 0 = empty .. 3 = full), rows padded to whole bytes.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

D = "/usr/share/fonts/TTF/"
FONTS = [
    # name, file, pixel size, first char, last char, crop to the charset's ink (True) or keep full line height
    ("FONT_S", "JetBrainsMonoNLNerdFontMono-Medium.ttf", 20, 32, 126, False),
    ("FONT_M", "JetBrainsMonoNLNerdFontMono-Bold.ttf", 30, 32, 126, False),
    ("FONT_L", "JetBrainsMonoNLNerdFontMono-ExtraBold.ttf", 112, ord("0"), ord(":"), True),
]


def build(name, fname, size, first, last, crop):
    f = ImageFont.truetype(D + fname, size)
    chars = [chr(c) for c in range(first, last + 1)]
    w = round(f.getlength("M"))
    asc, desc = f.getmetrics()
    top, bot = 0, asc + desc
    if crop:
        boxes = [f.getbbox(ch) for ch in chars]
        top, bot = min(b[1] for b in boxes) - 1, max(b[3] for b in boxes) + 1
    h = bot - top
    stride = (w + 3) // 4
    data = []
    for ch in chars:
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((0, -top), ch, font=f, fill=255)
        px = im.load()
        for y in range(h):
            row = [0] * stride
            for x in range(w):
                v = (px[x, y] + 32) // 85          # 0..3
                row[x >> 2] |= min(v, 3) << ((x & 3) * 2)
            data += row
    body = ",".join(str(b) for b in data)
    return (f"static const uint8_t {name.lower()}_data[{len(data)}] = {{{body}}};\n"
            f"static const font_t {name} = {{{w}, {h}, {first}, {len(chars)}, {stride}, {name.lower()}_data}};\n"), len(data)


out = ["/* generated by tools/gen_font.py from JetBrains Mono (SIL Open Font License) */\n",
       "typedef struct { uint8_t w, h, first, count; uint16_t stride; const uint8_t *data; } font_t;\n"]
total = 0
for spec in FONTS:
    s, n = build(*spec)
    out.append(s)
    total += n
open(sys.argv[1], "w").write("".join(out))
print("fonts written:", sys.argv[1], total, "bytes")
