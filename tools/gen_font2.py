"""Fonts + icons for ONKAR OS v16 -> onkar_font2.h       python3 tools/gen_font2.py OUT.h   (system python, needs PIL + raqm)
Text: Adwaita Sans (Inter-based, variable weight/optical size). Icons: Material Symbols Rounded (filled), by ligature name.
Each glyph is cropped to its ink, 16 alpha levels (4 bit), stored as a nibble stream:
   1..14  one pixel of that alpha
   0 n    n+1 transparent pixels (1..16)       15 n   n+1 opaque pixels (1..16)
Rows are not padded. Every 8th row starts at a checkpoint (u16 nibble offset, table in front of the stream) so a strip
renderer can start decoding mid-glyph.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SANS = "/usr/share/fonts/Adwaita/AdwaitaSans-Regular.ttf"
ICONS = "/usr/share/fonts/ttf-material-symbols-variable/MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf"
ASCII = [chr(c) for c in range(32, 127)]
DIGITS = list("0123456789:.")
GAMMA = 0.85            # >1 thinner, <1 bolder edges: AMOLED + sRGB blending makes thin text look starved

ICON_NAMES = ["timer", "hourglass_top", "brush", "flashlight_on", "self_improvement", "settings", "info",
              "bluetooth", "bluetooth_disabled", "light_mode", "dark_mode", "power_settings_new", "watch", "sync"]

FONTS = [
    # name, file, px, axes {opsz, wght} or icon axes, chars, tabular digits
    ("F_S", SANS, 22, (22, 500), ASCII, False),
    ("F_M", SANS, 28, (28, 500), ASCII, False),
    ("F_L", SANS, 36, (32, 650), ASCII, False),
    ("F_D", SANS, 84, (32, 600), DIGITS, True),
    ("F_H", SANS, 206, (32, 620), DIGITS[:10], True),
    ("F_I", ICONS, 44, None, ICON_NAMES, False),
    ("F_IS", ICONS, 30, None, ["bluetooth", "bluetooth_disabled", "timer", "watch", "delete", "light_mode"], False),
]


def font_obj(path, px, axes):
    f = ImageFont.truetype(path, px, layout_engine=ImageFont.Layout.RAQM)
    if path == SANS:
        f.set_variation_by_axes(list(axes))
    else:
        f.set_variation_by_axes([1, 0, 48 if px > 36 else 24, 500])      # FILL GRAD opsz wght
    return f


def encode(img):
    w, h = img.size
    px = img.load()
    rows = []
    for y in range(h):
        r = []
        for x in range(w):
            a = px[x, y] / 255.0
            v = int(round((a ** GAMMA) * 15)) if a > 0 else 0
            r.append(v)
        rows.append(r)
    nib, cps = [], []
    for y, r in enumerate(rows):
        if y % 8 == 0:
            cps.append(len(nib))
        x = 0
        while x < w:
            v = r[x]
            if v in (0, 15):
                n = 1
                while x + n < w and r[x + n] == v and n < 16:
                    n += 1
                nib += [v, n - 1]
                x += n
            else:
                nib.append(v)
                x += 1
    if len(nib) % 2:
        nib.append(0)
    data = bytearray()
    for cp in cps:
        data += cp.to_bytes(2, "little")
    data += bytes((nib[i] | (nib[i + 1] << 4)) for i in range(0, len(nib), 2))
    return bytes(data)


def build(name, path, px, axes, chars, tab):
    f = font_obj(path, px, axes)
    asc, desc = f.getmetrics()
    icon = path == ICONS
    glyphs, blob = [], bytearray()
    cell = 0
    if tab:
        cell = max(round(f.getlength(c)) for c in "0123456789")
    for ch in chars:
        l, t, r, b = f.getbbox(ch, anchor="ls")
        adv = round(f.getlength(ch))
        if r <= l or b <= t:
            glyphs.append((len(blob), 0, 0, 0, 0, adv))
            continue
        w, h = r - l, b - t
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor="ls")
        ox, oy = l, t + asc
        if tab and ch.isdigit():
            ox = (cell - w) // 2
            adv = cell
        if icon:
            ox, oy, adv = 0, 0, w
        off = len(blob)
        blob += encode(im)
        glyphs.append((off, w, h, ox, oy, adv))
    lname = name.lower()
    out = [f"static const gl_t {lname}_g[{len(glyphs)}] = {{" +
           ",".join(f"{{{o},{w},{h},{a},{x},{y}}}" for o, w, h, x, y, a in glyphs) + "};\n",
           f"static const uint8_t {lname}_d[{len(blob)}] = {{" + ",".join(str(v) for v in blob) + "};\n",
           f"static const font2_t {name} = {{{lname}_g, {lname}_d, {ord(chars[0]) if not icon else 0}, {len(chars)}, "
           f"{asc + desc}, {asc}}};\n"]
    if icon:
        out.append("".join(f"#define {name}_{n.upper()} {i}\n" for i, n in enumerate(chars)))
    return "".join(out), len(blob) + 12 * len(glyphs)


hdr = ["/* generated by tools/gen_font2.py: Adwaita Sans (SIL OFL), Material Symbols Rounded (Apache 2.0) */\n",
       "typedef struct { uint32_t off; uint8_t w, h, adv; int8_t ox; int16_t oy; } gl_t;\n",
       "typedef struct { const gl_t *g; const uint8_t *d; uint8_t first, count, line_h, asc; } font2_t;\n"]
total = 0
for spec in FONTS:
    s, n = build(*spec)
    hdr.append(s)
    total += n
    print(f"{spec[0]:5s} {spec[2]:4d}px  {n:6d} bytes")
open(sys.argv[1], "w").write("".join(hdr))
print("total", total, "bytes ->", sys.argv[1])
